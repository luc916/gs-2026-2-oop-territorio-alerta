package br.com.citizentech.persistencia;


import java.sql.*;

public class Banco {
    private final String url;
    public Banco(String url) { this.url = url; }
    public Connection conectar() throws SQLException { return DriverManager.getConnection(url, "sa", ""); }
    public void inicializar() throws SQLException {
        try (Connection c = conectar(); Statement s = c.createStatement()) {
            s.executeUpdate("CREATE TABLE IF NOT EXISTS medicao (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, sensor VARCHAR(40) NOT NULL, valor DOUBLE PRECISION NOT NULL, instante TIMESTAMP NOT NULL)");
            s.executeUpdate("CREATE TABLE IF NOT EXISTS alerta (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, sensor VARCHAR(40) NOT NULL, nivel VARCHAR(20) NOT NULL, previsto DOUBLE PRECISION NOT NULL, limite DOUBLE PRECISION NOT NULL, justificativa VARCHAR(1000) NOT NULL, instante TIMESTAMP NOT NULL)");
        }
    }
}
